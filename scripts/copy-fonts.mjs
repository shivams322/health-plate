// Copies the app's three typefaces from @fontsource into web/fonts so the site and apps
// work offline and never call Google's servers. Keeps Latin, Latin Extended and Devanagari
// (for Hindi food names) in woff2 only.
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'web', 'fonts');
const filesDir = join(outDir, 'files');
mkdirSync(filesDir, { recursive: true });

const FAMILIES = [
  { pkg: 'baloo-2', weights: [500, 600, 700, 800] },
  { pkg: 'mukta', weights: [400, 500, 600, 700] },
  { pkg: 'ibm-plex-mono', weights: [400, 500] },
];
const KEEP = /-(latin|latin-ext|devanagari)-\d+-normal/;

let css = '/* Generated by scripts/copy-fonts.mjs from @fontsource packages (SIL Open Font License). */\n';
let count = 0;
for (const { pkg, weights } of FAMILIES) {
  const pkgDir = join(root, 'node_modules', '@fontsource', pkg);
  for (const w of weights) {
    const src = readFileSync(join(pkgDir, `${w}.css`), 'utf8');
    for (const block of src.split(/(?=\/\*)/)) {
      const m = block.match(/url\(\.\/files\/([^)]+?\.woff2)\)/);
      if (!m || !KEEP.test(m[1])) continue;
      copyFileSync(join(pkgDir, 'files', m[1]), join(filesDir, m[1]));
      count++;
      css += block
        .replace(/src:[^;]+;/, `src: url(files/${m[1]}) format('woff2');`)
        .trimEnd() + '\n\n';
    }
  }
}
writeFileSync(join(outDir, 'fonts.css'), css);
console.log(`Copied ${count} font files to web/fonts`);
